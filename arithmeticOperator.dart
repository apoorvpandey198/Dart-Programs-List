void main() {
  int a = 10, b = 20;
  print("Sum of A and B : ${a + b}");
  // Subtraction of b-a=?;
  var subtract = b - a;
  print(subtract);
  // Multiplication
  var Multiplication = a * b;
  print(Multiplication);
  // division
  var div = b / a;
  print(div);
  // reminder
  var reminder = b % a;
  print(reminder);
  // integer division
  var integer_div = a ~/ b;
  print(integer_div);
}
